-- M11C — Game V2 context: explicit US-context adapters, curated recipes with
-- provenance, longitudinal resurfacing and perspective rotation.
--
-- Additive on top of M11B (20260930150000_m11b_game_v2_core.sql); apply the
-- two together. Nothing here writes to the sources it reads, and no adapter
-- reads Daily Question answers or Left for You content:
--   da_vivere_idea / da_vivere_lived  public.bucket_items (shared list)
--   calendar_upcoming / calendar_past public.calendar_entries, entry_type
--                                     'shared' only (personal entries never)
--   moment                            public.moments (shared), caption only
--   conservati                        public.conserva_contributions COUNT and
--                                     timestamp only, never the kept item
--   longitudinal                      the couple's own revealed Game V2 answers
-- Every candidate is materialized as an immutable item snapshot with its
-- provenance in game_session_items.context; a source changed or deleted later
-- never rewrites a played round.
--
-- Bond XP is deliberately NOT awarded: no Bond XP writer exists in
-- the repository to reuse safely, so Game V2 defers it (decision log).

-- ---------------------------------------------------------------------------
-- 1. Curated recipes (editorial authority for context prompts).
-- ---------------------------------------------------------------------------

create table public.game_v2_recipes (
  id text primary key check (id ~ '^[a-z_]+-[0-9]{3}$'),
  version integer not null default 1 check (version > 0),
  adapter text not null check (adapter in ('da_vivere_idea', 'da_vivere_lived', 'calendar_upcoming',
    'calendar_past', 'moment', 'conservati', 'longitudinal')),
  family text check (family is null or family = any (private.game_v2_families())),
  mechanic text not null default 'reciprocal' check (mechanic = 'reciprocal'),
  answer_kind text not null check (answer_kind in ('open', 'choice')),
  question_text text not null check (char_length(btrim(question_text)) between 12 and 240
    or question_text = '{previous_question}'),
  options jsonb not null default '[]'::jsonb,
  depth smallint not null check (depth between 1 and 3),
  topic text not null check (topic ~ '^ctx_[a-z_]+$'),
  cooldown_class text not null references public.game_v2_cooldowns(cooldown_class),
  kind_label text not null check (char_length(btrim(kind_label)) between 3 and 40),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  check (split_part(id, '-', 1) = adapter),
  -- A longitudinal item keeps the family of the prompt it resurfaces.
  check ((adapter = 'longitudinal') = (family is null)),
  check (adapter <> 'longitudinal' or (question_text = '{previous_question}' and answer_kind = 'open'
    and cooldown_class = 'longitudinal')),
  check (adapter = 'longitudinal' or cooldown_class = 'context'),
  check (adapter not in ('da_vivere_idea', 'da_vivere_lived', 'calendar_upcoming', 'calendar_past', 'moment')
    or question_text like '%{title}%'),
  check (case when jsonb_typeof(options) = 'array' then
    (answer_kind = 'open' and jsonb_array_length(options) = 0) or
    (answer_kind = 'choice' and jsonb_array_length(options) between 2 and 4)
    else false end)
);

comment on table public.game_v2_recipes is
  'M11C curated Game V2 context recipes. Source of truth: supabase/game-v2/recipes/<adapter>.json (generated seed). Server-only.';

