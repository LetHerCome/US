-- ---------------------------------------------------------------------------
-- 2. Rendering helpers. Titles are sanitized before they can become a
--    question: one line, 3-60 characters, with letters, no links, no quotes
--    that would break the «…» framing.
-- ---------------------------------------------------------------------------

create function private.game_v2_clean_title(raw text)
returns text language sql immutable set search_path = '' as $$
  select case when t is null or char_length(t) not between 3 and 60 or t !~ '[[:alpha:]]'
      or t ~* '(https?://|www\.|[a-z0-9-]+\.(com|it|net|org)\y)' then null else t end
  from (select nullif(btrim(regexp_replace(translate(coalesce(raw, ''), '«»“”"', '     '), '\s+', ' ', 'g')), '') t) x;
$$;

create function private.game_v2_month_name(d date)
returns text language sql immutable set search_path = '' as $$
  select (array['gennaio', 'febbraio', 'marzo', 'aprile', 'maggio', 'giugno', 'luglio', 'agosto',
    'settembre', 'ottobre', 'novembre', 'dicembre'])[extract(month from d)::integer];
$$;

-- "a marzo", "ad aprile", "a marzo 2025" (year only when it differs).
create function private.game_v2_when_label(d date, at_date date)
returns text language sql immutable set search_path = '' as $$
  select case when extract(month from d) in (4, 8) then 'ad ' else 'a ' end || private.game_v2_month_name(d)
    || case when extract(year from d) <> extract(year from at_date) then ' ' || extract(year from d)::integer::text else '' end;
$$;

-- "12 ottobre".
create function private.game_v2_day_label(d date)
returns text language sql immutable set search_path = '' as $$
  select extract(day from d)::integer::text || ' ' || private.game_v2_month_name(d);
$$;

create function private.game_v2_fill(template text, source jsonb)
returns text language sql immutable set search_path = '' as $$
  select replace(replace(replace(replace(template,
    '{title}', coalesce(source->>'title', '')), '{date}', coalesce(source->>'date', '')),
    '{when}', coalesce(source->>'when', '')), '{previous_question}', coalesce(source->>'previous_question', ''));
$$;

-- Joins a set of source snapshots with the active recipes of one adapter.
-- Every candidate carries its provenance; the client shows only kind_label.
create function private.game_v2_recipe_candidates(target_family text, target_adapter text, source_kind text,
  sources jsonb, at_time timestamptz)
returns setof private.game_v2_candidate language sql stable set search_path = '' as $$
  select ('recipe:' || r.id || ':' || source_kind || ':' || (s->>'id')), r.family, r.mechanic, r.answer_kind,
    private.game_v2_fill(r.question_text, s), null::text, r.options, r.depth, r.topic, source_kind, s->>'id',
    r.id, r.version, null::uuid, null::integer,
    jsonb_build_object('kind', r.adapter, 'kind_label', private.game_v2_fill(r.kind_label, s),
      'source_type', source_kind, 'source_id', s->>'id', 'title', s->>'title', 'when', coalesce(s->>'when', s->>'date'),
      'recipe_id', r.id, 'recipe_version', r.version, 'captured_at', at_time),
    r.cooldown_class, 70 + 2 * (r.depth - 1), null::integer, null::boolean, null::timestamptz
  from jsonb_array_elements(coalesce(sources, '[]'::jsonb)) s
  join public.game_v2_recipes r on r.adapter = target_adapter and r.active
    and (target_family = 'per_voi' or r.family = target_family);
$$;

-- ---------------------------------------------------------------------------
-- 3. Explicit adapters. Each one is isolated: a failing source (schema drift,
--    unexpected data) is logged and skipped, never breaks a round. Sources
--    rotate weekly with a deterministic hash, at most four objects each.
-- ---------------------------------------------------------------------------

create function private.game_v2_ctx_da_vivere(target_couple uuid, target_family text, at_time timestamptz)
returns setof private.game_v2_candidate language plpgsql stable set search_path = '' as $$
declare ideas jsonb; lived jsonb; at_date date := (at_time at time zone 'Europe/Rome')::date;
  week text := private.game_v2_week_start(at_time)::text;
begin
  select coalesce(jsonb_agg(x.src), '[]'::jsonb) into ideas from (
    select jsonb_build_object('id', b.id::text, 'title', t.title) src
    from public.bucket_items b cross join lateral (select private.game_v2_clean_title(b.title) title) t
    where b.couple_id = target_couple and b.status in ('idea', 'scheduled') and t.title is not null
    order by md5(target_couple::text || ':' || b.id::text || ':' || week) limit 4) x;
  select coalesce(jsonb_agg(x.src), '[]'::jsonb) into lived from (
    select jsonb_build_object('id', b.id::text, 'title', t.title,
      'when', private.game_v2_when_label((b.completed_at at time zone 'Europe/Rome')::date, at_date)) src
    from public.bucket_items b cross join lateral (select private.game_v2_clean_title(b.title) title) t
    where b.couple_id = target_couple and b.status = 'lived' and t.title is not null
      and b.completed_at is not null
      and (b.completed_at at time zone 'Europe/Rome')::date between at_date - 730 and at_date - 3
    order by md5(target_couple::text || ':' || b.id::text || ':' || week) limit 4) x;
  return query select * from private.game_v2_recipe_candidates(target_family, 'da_vivere_idea', 'da_vivere', ideas, at_time);
  return query select * from private.game_v2_recipe_candidates(target_family, 'da_vivere_lived', 'da_vivere', lived, at_time);
exception when others then
  raise warning 'game_v2 context adapter da_vivere skipped: %', sqlerrm;
  return;
end;
$$;

create function private.game_v2_ctx_calendar(target_couple uuid, target_family text, at_time timestamptz)
returns setof private.game_v2_candidate language plpgsql stable set search_path = '' as $$
declare upcoming jsonb; past jsonb; at_date date := (at_time at time zone 'Europe/Rome')::date;
  week text := private.game_v2_week_start(at_time)::text;
begin
  -- Shared entries only; an entry already represented by a Da vivere item is
  -- left to that adapter so the same plan never appears twice.
  with shared as (
    select e.id, private.game_v2_clean_title(e.title) title,
      coalesce((e.starts_at at time zone 'Europe/Rome')::date, e.start_date) as on_day
    from public.calendar_entries e
    where e.couple_id = target_couple and e.entry_type = 'shared'
      and not exists (select 1 from public.bucket_items b where b.calendar_entry_id = e.id)
  )
  select
    coalesce((select jsonb_agg(x.src) from (
      select jsonb_build_object('id', s.id::text, 'title', s.title, 'date', private.game_v2_day_label(s.on_day)) src
      from shared s where s.title is not null and s.on_day between at_date + 1 and at_date + 60
      order by s.on_day, s.id limit 4) x), '[]'::jsonb),
    coalesce((select jsonb_agg(x.src) from (
      select jsonb_build_object('id', s.id::text, 'title', s.title, 'when', private.game_v2_when_label(s.on_day, at_date)) src
      from shared s where s.title is not null and s.on_day between at_date - 365 and at_date - 7
      order by md5(target_couple::text || ':' || s.id::text || ':' || week) limit 4) x), '[]'::jsonb)
  into upcoming, past;
  return query select * from private.game_v2_recipe_candidates(target_family, 'calendar_upcoming', 'calendar', upcoming, at_time);
  return query select * from private.game_v2_recipe_candidates(target_family, 'calendar_past', 'calendar', past, at_time);
exception when others then
  raise warning 'game_v2 context adapter calendar skipped: %', sqlerrm;
  return;
end;
$$;

create function private.game_v2_ctx_moments(target_couple uuid, target_family text, at_time timestamptz)
returns setof private.game_v2_candidate language plpgsql stable set search_path = '' as $$
declare src jsonb; at_date date := (at_time at time zone 'Europe/Rome')::date;
  week text := private.game_v2_week_start(at_time)::text;
begin
  select coalesce(jsonb_agg(x.src), '[]'::jsonb) into src from (
    select jsonb_build_object('id', m.id::text, 'title', t.title, 'when', private.game_v2_when_label(t.on_day, at_date)) src
    from public.moments m
    cross join lateral (select private.game_v2_clean_title(m.caption) title,
      coalesce(m.moment_date, (m.created_at at time zone 'Europe/Rome')::date) as on_day) t
    where m.couple_id = target_couple and t.title is not null and t.on_day between at_date - 730 and at_date - 14
    order by md5(target_couple::text || ':' || m.id::text || ':' || week) limit 4) x;
  return query select * from private.game_v2_recipe_candidates(target_family, 'moment', 'moment', src, at_time);
exception when others then
  raise warning 'game_v2 context adapter moments skipped: %', sqlerrm;
  return;
end;
$$;

-- Metadata only: whether the couple kept something recently. The kept items,
-- their sender and their text are never read.
create function private.game_v2_ctx_conservati(target_couple uuid, target_family text, at_time timestamptz)
returns setof private.game_v2_candidate language plpgsql stable set search_path = '' as $$
declare kept boolean;
begin
  select exists (select 1 from public.conserva_contributions c
    where c.couple_id = target_couple and c.created_at between at_time - interval '365 days' and at_time) into kept;
  if not kept then return; end if;
  return query select * from private.game_v2_recipe_candidates(target_family, 'conservati', 'conservati',
    jsonb_build_array(jsonb_build_object('id', 'conservati')), at_time);
exception when others then
  raise warning 'game_v2 context adapter conservati skipped: %', sqlerrm;
  return;
end;
$$;

-- Longitudinal resurfacing: a curated prompt marked longitudinal, answered
-- openly by both partners in a revealed round at least 90 days ago and not
-- played since, comes back as itself. The earlier answers are shown only in
-- the new reveal (see m11a_session_state below).
create function private.game_v2_ctx_longitudinal(target_couple uuid, target_family text, at_time timestamptz)
returns setof private.game_v2_candidate language plpgsql stable set search_path = '' as $$
declare at_date date := (at_time at time zone 'Europe/Rome')::date;
begin
  return query
  with plays as (
    select i.id item_id, i.source_ref catalog_id, s.started_at, s.completed_at,
      (select count(*) from public.game_session_answers a where a.item_id = i.id and a.answer_text is not null) answered
    from public.game_session_items i join public.game_sessions s on s.id = i.session_id
    where s.couple_id = target_couple and s.engine_version = 2 and i.source_type in ('curated', 'game_history')
  ), last_play as (
    select distinct on (p.catalog_id) p.catalog_id, p.started_at last_started from plays p
    order by p.catalog_id, p.started_at desc
  ), previous as (
    select distinct on (p.catalog_id) p.catalog_id, p.item_id, p.started_at, p.completed_at from plays p
    where p.completed_at is not null and p.answered = 2
    order by p.catalog_id, p.completed_at desc
  )
  select ('longitudinal:' || c.id), c.family, 'reciprocal'::text, 'open'::text,
    private.game_v2_fill(r.question_text, jsonb_build_object('previous_question', c.question_text)),
    null::text, '[]'::jsonb, c.depth, c.topic, 'game_history'::text, c.id, r.id, r.version, null::uuid, null::integer,
    jsonb_build_object('kind', 'longitudinal',
      'kind_label', private.game_v2_fill(r.kind_label, jsonb_build_object('when',
        private.game_v2_when_label((pv.started_at at time zone 'Europe/Rome')::date, at_date))),
      'source_type', 'game_history', 'source_id', c.id, 'previous_item_id', pv.item_id,
      'previous_played_at', pv.started_at, 'recipe_id', r.id, 'recipe_version', r.version, 'captured_at', at_time),
    r.cooldown_class, 72, null::integer, null::boolean, null::timestamptz
  from public.game_v2_catalog c
  join previous pv on pv.catalog_id = c.id
  join last_play lp on lp.catalog_id = c.id
  join public.game_v2_recipes r on r.adapter = 'longitudinal' and r.active
  where c.active and c.longitudinal and c.mechanic = 'reciprocal' and c.answer_kind = 'open'
    and (target_family = 'per_voi' or c.family = target_family)
    and lp.last_started <= at_time - interval '90 days'
  -- One resurfacing at a time: the prompt answered longest ago.
  order by pv.started_at, c.id
  limit 1;
exception when others then
  raise warning 'game_v2 context adapter longitudinal skipped: %', sqlerrm;
  return;
end;
$$;

-- The M11B plug-in point, now wired to the explicit adapters.
create or replace function private.game_v2_context_candidates(target_couple uuid, target_family text, at_time timestamptz)
returns setof private.game_v2_candidate language sql stable set search_path = '' as $$
  select * from private.game_v2_ctx_da_vivere(target_couple, target_family, at_time)
  union all select * from private.game_v2_ctx_calendar(target_couple, target_family, at_time)
  union all select * from private.game_v2_ctx_moments(target_couple, target_family, at_time)
  union all select * from private.game_v2_ctx_conservati(target_couple, target_family, at_time)
  union all select * from private.game_v2_ctx_longitudinal(target_couple, target_family, at_time);
$$;

