// US content 1.1 (22/10/2026): more Daily Questions, Game V2 prompts, Swipe
// cards and couple missions, inspired by the formats of Paired and written in
// the voice of US (docs/missions/content-1-1.md). The drafts in ./content-1-1
// are the human-reviewable source; the migration carries the SQL generated
// from them between the `-- content-1-1:begin/end` markers, and
// tests/content-1-1-catalog.test.js fails when the two drift apart.
// Insert only: every row is new, nothing existing changes. Regenerate with:
//   node scripts/build-content-1-1-sql.mjs
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './catalog-contract.mjs';

export const REPO = path.resolve(ROOT, '../..');
export const DIR = path.join(ROOT, 'content-1-1');
export const MIGRATION = 'supabase/migrations/20261022160549_content_1_1.sql';
export const BLOCK = 'content-1-1';
export const NEW_GAMES = { quanto_mi_conosci: [53, 76], ridete: [41, 60], scopritevi: [43, 58], confrontatevi: [41, 52], rivivete: [29, 40] };
export const NEW_SWIPE = [73, 102];
export const DAILY_SEQUENCES = [27, 52];
export const WEEKDAY = { noi_adesso: 1, scoprirsi: 2, ricordi: 3, desideri: 4, vicinanza: 5, gioco: 6, profonda: 7 };
export const QUEST_XP = { common: 25, uncommon: 40, rare: 60, epic: 100 };
export const QUEST_MODES = ['any', 'near', 'far'];
export const QUEST_CATEGORIES = ['memory', 'surprise', 'fun', 'connection', 'adventure', 'chill', 'discover'];

const readJson = (file) => JSON.parse(fs.readFileSync(path.join(DIR, file), 'utf8'));

export function drafts() {
  return { daily: readJson('daily.json'), games: readJson('games.json'), swipe: readJson('swipe.json'), quests: readJson('quests.json') };
}

const familyOf = (id) => id.split('-')[0];
const sqlText = (value) => (value === null || value === undefined ? 'null' : `'${String(value).replace(/'/g, "''")}'`);
const sqlJson = (value) => `${sqlText(JSON.stringify(value ?? []))}::jsonb`;
const tuple = (values) => `  (${values.join(', ')})`;

export function contentSql() {
  const d = drafts();
  const daily = d.daily.new.map((r) => {
    const theme = familyOf(r.id);
    return tuple([sqlText(r.id), String(WEEKDAY[theme]), String(Number(r.id.split('-')[1])), sqlText(r.question), sqlText(theme), 'true', sqlText(r.question_en)]);
  });
  const games = d.games.new.map((n) => tuple([
    sqlText(n.id), '1', sqlText(familyOf(n.id)), sqlText('curated'), sqlText(n.mechanic), sqlText(n.answer_kind),
    sqlText(n.question_text), sqlText(n.predict_text ?? null), sqlJson(n.options || []), String(n.depth), sqlText(n.topic),
    sqlText(n.cooldown_class), 'false', sqlText(n.question_text_en), sqlText(n.predict_text_en ?? null), sqlJson(n.options_en || []),
  ]));
  const swipe = d.swipe.new.map((n) => tuple([
    sqlText(n.id), '1', sqlText(n.question_text), sqlJson(n.options), sqlText(n.topic), 'true', sqlText(n.question_text_en), sqlJson(n.options_en),
  ]));
  const quests = d.quests.new.map((q) => tuple([
    sqlText(q.key), sqlText(q.title), sqlText(q.category), sqlText(q.rarity), String(q.xp), sqlText(q.mode), 'true', sqlText(q.title_en),
  ]));
  return [
    `-- ${BLOCK}:begin (generated by scripts/build-content-1-1-sql.mjs from supabase/game-v2/content-1-1; do not edit by hand)`,
    '',
    `-- Daily Question bank: ${daily.length} new questions (sequences ${DAILY_SEQUENCES.join('-')} of each weekday), Italian and English.`,
    'insert into public.daily_question_templates (id, weekday_slot, sequence, question, theme, active, question_en) values',
    daily.join(',\n'),
    'on conflict (id) do nothing;',
    '',
    `-- Game V2 catalog: ${games.length} new prompts, Italian and English.`,
    'insert into public.game_v2_catalog (id, version, family, source_type, mechanic, answer_kind, question_text, predict_text, options, depth, topic, cooldown_class, longitudinal, question_text_en, predict_text_en, options_en) values',
    games.join(',\n'),
    'on conflict (id) do nothing;',
    '',
    `-- Swipe V1: ${swipe.length} new cards, Italian and English.`,
    'insert into private.game_swipe_v1_catalog (id, version, question_text, options, topic, active, question_text_en, options_en) values',
    swipe.join(',\n'),
    'on conflict (id) do nothing;',
    '',
    `-- Couple missions: ${quests.length} new weekly templates, Italian and English.`,
    'insert into public.bond_quest_templates (key, title, category, rarity, xp, mode, active, title_en) values',
    quests.join(',\n'),
    'on conflict (key) do nothing;',
    '',
    `-- ${BLOCK}:end`,
  ].join('\n');
}
