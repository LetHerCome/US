// US content 1.3 «hot» (founder, 28/11/2026): two US Plus themes a little
// spicier than the rest of the catalog, for adult couples — piccante (flirt,
// attraction, kisses, seduction, daring dates) and desideri (closeness,
// romantic fantasies, cuddles, surprises in bed said with elegance). Every
// new row is plus. Same pipeline as content 1.2: the drafts in ./content-1-3
// are the human-reviewable source; the migration carries the SQL generated
// from them between the `-- content-1-3:begin/end` markers, and
// tests/content-1-3-catalog.test.js fails when the two drift apart. Insert
// only: every row is new, nothing existing changes.
// Regenerate with:
//   node scripts/build-content-1-3-sql.mjs
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './catalog-contract.mjs';

export const REPO = path.resolve(ROOT, '../..');
export const DIR = path.join(ROOT, 'content-1-3');
export const MIGRATION = 'supabase/migrations/20261128115152_contenuti_hot.sql';
export const BLOCK = 'content-1-3';
export const NEW_GAMES = { quanto_mi_conosci: [109, 120], ridete: [92, 99], scopritevi: [91, 98], confrontatevi: [84, 91], rivivete: [71, 76] };
export const NEW_SWIPE = [135, 142];
// The theme is the first part of every new topic («piccante_prima_mossa»).
export const THEMES = ['piccante', 'desideri'];

const readJson = (file) => JSON.parse(fs.readFileSync(path.join(DIR, file), 'utf8'));

export function drafts() {
  return { games: readJson('games.json'), swipe: readJson('swipe.json') };
}

const familyOf = (id) => id.split('-')[0];
const sqlText = (value) => (value === null || value === undefined ? 'null' : `'${String(value).replace(/'/g, "''")}'`);
const sqlJson = (value) => `${sqlText(JSON.stringify(value ?? []))}::jsonb`;
const sqlBool = (value) => (value ? 'true' : 'false');
const tuple = (values) => `  (${values.join(', ')})`;

export function contentSql() {
  const d = drafts();
  const games = d.games.new.map((n) => tuple([
    sqlText(n.id), '1', sqlText(familyOf(n.id)), sqlText('curated'), sqlText(n.mechanic), sqlText(n.answer_kind),
    sqlText(n.question_text), sqlText(n.predict_text ?? null), sqlJson(n.options || []), String(n.depth), sqlText(n.topic),
    sqlText(n.cooldown_class), 'false', sqlBool(n.plus), sqlText(n.question_text_en), sqlText(n.predict_text_en ?? null), sqlJson(n.options_en || []),
  ]));
  const swipe = d.swipe.new.map((n) => tuple([
    sqlText(n.id), '1', sqlText(n.question_text), sqlJson(n.options), sqlText(n.topic), 'true', sqlBool(n.plus),
    sqlText(n.question_text_en), sqlJson(n.options_en),
  ]));
  const plus = (rows) => rows.filter((r) => r.plus).length;
  return [
    `-- ${BLOCK}:begin (generated by scripts/build-content-1-3-sql.mjs from supabase/game-v2/content-1-3; do not edit by hand)`,
    '',
    `-- Game V2 catalog: ${games.length} new prompts (${plus(d.games.new)} plus), Italian and English.`,
    'insert into public.game_v2_catalog (id, version, family, source_type, mechanic, answer_kind, question_text, predict_text, options, depth, topic, cooldown_class, longitudinal, plus, question_text_en, predict_text_en, options_en) values',
    games.join(',\n'),
    'on conflict (id) do nothing;',
    '',
    `-- Questo o quello: ${swipe.length} new cards (${plus(d.swipe.new)} plus), Italian and English.`,
    'insert into private.game_swipe_v1_catalog (id, version, question_text, options, topic, active, plus, question_text_en, options_en) values',
    swipe.join(',\n'),
    'on conflict (id) do nothing;',
    '',
    `-- ${BLOCK}:end`,
  ].join('\n');
}
