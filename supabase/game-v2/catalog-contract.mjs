// Game V2 — editorial contract shared by the SQL seed generator and the tests.
// The JSON files in ./catalog (curated prompts) and ./recipes (context
// recipes) are the human-reviewable source; the migrations carry the
// generated SQL block, and a test fails if the two drift apart.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.dirname(fileURLToPath(import.meta.url));
export const FAMILIES = ['scopritevi', 'confrontatevi', 'ridete', 'quanto_mi_conosci', 'rivivete', 'e_se'];
export const COOLDOWN_CLASSES = ['light', 'standard', 'deep', 'custom', 'context', 'longitudinal'];
export const PLACEHOLDERS = ['{subject}', '{francesco}', '{beatrice}', '{title}', '{date}', '{when}', '{previous_question}'];

// Obvious filler the mission explicitly rejects. A regex cannot judge whether
// a question is good; it only keeps the cheapest generic prompts out.
export const BANNED_FILLER = [
  /mare o montagna/i, /pizza o sushi/i, /film o serie/i, /chi (?:dei due )?è più geloso/i,
  /colore preferito/i, /sogno più grande/i, /dove vorresti viaggiare/i, /cibo preferito/i,
  /canzone preferita/i, /cane o gatto/i,
];

export function readEntries(dir) {
  const base = path.join(ROOT, dir);
  if (!fs.existsSync(base)) return [];
  return fs.readdirSync(base).filter((f) => f.endsWith('.json')).sort().flatMap((file) => {
    const family = file.replace(/\.json$/, '');
    return JSON.parse(fs.readFileSync(path.join(base, file), 'utf8')).map((entry) => ({ family, ...entry }));
  });
}

export const catalog = () => readEntries('catalog');

// Context recipes: one file per explicit adapter (the file name).
export const ADAPTERS = ['da_vivere_idea', 'da_vivere_lived', 'calendar_upcoming', 'calendar_past', 'moment', 'conservati', 'longitudinal'];
export function recipes() {
  const base = path.join(ROOT, 'recipes');
  if (!fs.existsSync(base)) return [];
  return fs.readdirSync(base).filter((f) => f.endsWith('.json')).sort().flatMap((file) =>
    JSON.parse(fs.readFileSync(path.join(base, file), 'utf8')).map((entry) => ({ adapter: file.replace(/\.json$/, ''), ...entry })));
}

const sqlText = (value) => (value === null || value === undefined ? 'null' : `'${String(value).replace(/'/g, "''")}'`);
const sqlJson = (value) => `${sqlText(JSON.stringify(value || []))}::jsonb`;

export function catalogSql(entries = catalog()) {
  const rows = entries.map((e) => `  (${[
    sqlText(e.id), String(e.version || 1), sqlText(e.family), sqlText(e.source_type || 'curated'),
    sqlText(e.mechanic), sqlText(e.answer_kind), sqlText(e.question_text), sqlText(e.predict_text ?? null),
    sqlJson(e.options), String(e.depth), sqlText(e.topic), sqlText(e.cooldown_class), e.longitudinal ? 'true' : 'false',
  ].join(', ')})`);
  return [
    '-- game-v2-catalog:begin (generated by scripts/build-game-v2-catalog-sql.mjs from supabase/game-v2/catalog; do not edit by hand)',
    'insert into public.game_v2_catalog (id, version, family, source_type, mechanic, answer_kind, question_text, predict_text, options, depth, topic, cooldown_class, longitudinal) values',
    `${rows.join(',\n')}`,
    'on conflict (id) do nothing;',
    '-- game-v2-catalog:end',
  ].join('\n');
}

export function recipesSql(entries = recipes()) {
  const rows = entries.map((e) => `  (${[
    sqlText(e.id), String(e.version || 1), sqlText(e.adapter), sqlText(e.family ?? null), sqlText(e.answer_kind),
    sqlText(e.question_text), sqlJson(e.options), String(e.depth), sqlText(e.topic), sqlText(e.cooldown_class), sqlText(e.kind_label),
  ].join(', ')})`);
  return [
    '-- game-v2-recipes:begin (generated by scripts/build-game-v2-catalog-sql.mjs recipes from supabase/game-v2/recipes; do not edit by hand)',
    'insert into public.game_v2_recipes (id, version, adapter, family, answer_kind, question_text, options, depth, topic, cooldown_class, kind_label) values',
    `${rows.join(',\n')}`,
    'on conflict (id) do nothing;',
    '-- game-v2-recipes:end',
  ].join('\n');
}

export function extractBlock(sql, name) {
  const start = sql.indexOf(`-- ${name}:begin`);
  const end = sql.indexOf(`-- ${name}:end`);
  if (start < 0 || end < 0) return null;
  return sql.slice(start, end + `-- ${name}:end`.length);
}
