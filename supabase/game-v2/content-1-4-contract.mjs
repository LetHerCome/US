// US content 1.4 «domande a scelta» (founder, 28/11/2026): almost every open
// Gioca prompt becomes multiple choice. Open stay only the longitudinal
// prompts (re-asked months later with «cosa avevate risposto»), the Rivivete
// prompts that ask for a detail of one precise memory (keep_open), the
// question of the day and the couple's own questions (neither is in this
// catalog). e_se is no longer offered on its own and stays as it is.
//
// The draft in ./content-1-4/games.json is the human-reviewable source: for
// every converted prompt it keeps the wording it replaces (`from`: version,
// Italian, English) next to the new one. The migration carries the SQL
// generated from it between the `-- content-1-4:begin/end` markers, and
// tests/content-1-4-catalog.test.js fails when the two drift apart.
//
// A converted prompt keeps its id, family, topic, depth, cooldown and plus,
// and takes version + 1 (the catalog rule: «bump version for a new wording»).
// Rounds already played keep their own copy in game_session_items, and the
// history (fingerprint 'catalog:<id>', Play Us items by id) does not depend
// on the version, so cooldowns and «già fatte di recente» carry over.
// Regenerate with:
//   node scripts/build-content-1-4-sql.mjs
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './catalog-contract.mjs';

export const REPO = path.resolve(ROOT, '../..');
export const DIR = path.join(ROOT, 'content-1-4');
export const MIGRATION = 'supabase/migrations/20261128122730_domande_a_scelta.sql';
export const BLOCK = 'content-1-4';
export const FAMILIES = ['ridete', 'scopritevi', 'confrontatevi', 'rivivete'];

export function drafts() {
  return JSON.parse(fs.readFileSync(path.join(DIR, 'games.json'), 'utf8'));
}

// One line per prompt, in the order of the draft. Dollar quoting keeps the
// Italian as it is (’ « » and no doubled quotes).
const TAG = '$changes$';
const line = (r) => JSON.stringify({
  id: r.id,
  from_version: r.from.version,
  from: r.from.question_text,
  from_en: r.from.question_text_en,
  question_text: r.question_text,
  options: r.options,
  question_text_en: r.question_text_en,
  options_en: r.options_en,
});

export function contentSql() {
  const d = drafts();
  const rows = d.convert;
  const json = rows.map(line);
  if (json.some((l) => l.includes(TAG))) throw new Error(`${TAG} inside the content`);
  const count = (family) => rows.filter((r) => r.id.startsWith(`${family}-`)).length;
  return [
    `-- ${BLOCK}:begin (generated by scripts/build-content-1-4-sql.mjs from supabase/game-v2/content-1-4; do not edit by hand)`,
    '',
    `-- ${rows.length} open prompts become choice: ${FAMILIES.map((f) => `${f} ${count(f)}`).join(', ')}.`,
    '-- Each line: the wording it replaces (from_version, from, from_en) and the new one.',
    'do $content_1_4$',
    'declare',
    `  changes constant jsonb := ${TAG}[`,
    json.map((l, i) => (i < json.length - 1 ? `${l},` : l)).join('\n'),
    `]${TAG}::jsonb;`,
    '  r record;',
    'begin',
    '  -- Every prompt must still be the open wording it replaces, or the choice',
    '  -- this migration writes (a re-apply). Anything else stops before any change.',
    '  for r in',
    '    select e->>\'id\' as id, e, c.id as found, c.version, c.answer_kind, c.active, c.longitudinal,',
    '           c.question_text, c.question_text_en, c.options, c.options_en',
    '      from pg_catalog.jsonb_array_elements(changes) e',
    '      left join public.game_v2_catalog c on c.id = e->>\'id\'',
    '  loop',
    '    if r.found is null then',
    '      raise exception using errcode = \'P0001\', message = \'content 1.4: \' || r.id || \' is missing\';',
    '    end if;',
    '    if not (',
    '      (r.version = (r.e->>\'from_version\')::integer and r.answer_kind = \'open\' and r.active and not r.longitudinal',
    '        and r.question_text = r.e->>\'from\' and r.question_text_en is not distinct from r.e->>\'from_en\')',
    '      or',
    '      (r.version = (r.e->>\'from_version\')::integer + 1 and r.answer_kind = \'choice\'',
    '        and r.question_text = r.e->>\'question_text\' and r.options = r.e->\'options\'',
    '        and r.question_text_en = r.e->>\'question_text_en\' and r.options_en = r.e->\'options_en\')',
    '    ) then',
    '      raise exception using errcode = \'P0001\', message = \'content 1.4: \' || r.id || \' is not the expected prompt\',',
    '        detail = \'version \' || r.version || \', \' || r.answer_kind || \': \' || r.question_text;',
    '    end if;',
    '  end loop;',
    '',
    '  update public.game_v2_catalog as c',
    '     set answer_kind = \'choice\',',
    '         question_text = e->>\'question_text\',',
    '         options = e->\'options\',',
    '         question_text_en = e->>\'question_text_en\',',
    '         options_en = e->\'options_en\',',
    '         version = c.version + 1',
    '    from pg_catalog.jsonb_array_elements(changes) e',
    '   where c.id = e->>\'id\'',
    '     and c.version = (e->>\'from_version\')::integer',
    '     and c.answer_kind = \'open\';',
    '',
    '  -- Postcondition: every prompt of the list is a choice with 3-4 options,',
    '  -- the same number in English.',
    '  if exists (select 1 from pg_catalog.jsonb_array_elements(changes) e',
    '              join public.game_v2_catalog c on c.id = e->>\'id\'',
    '             where c.answer_kind <> \'choice\' or pg_catalog.jsonb_array_length(c.options) not between 3 and 4',
    '                or pg_catalog.jsonb_array_length(c.options_en) <> pg_catalog.jsonb_array_length(c.options)) then',
    '    raise exception using errcode = \'P0001\', message = \'content 1.4: a converted prompt has no 3-4 options\';',
    '  end if;',
    'end;',
    '$content_1_4$;',
    '',
    `-- ${BLOCK}:end`,
  ].join('\n');
}
