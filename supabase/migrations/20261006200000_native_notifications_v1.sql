-- 20261006200000_native_notifications_v1.sql
-- Native Notifications V1: native push registration per physical app
-- installation (docs/native/NATIVE_NOTIFICATIONS_V1.md). Forward-only, newer
-- than every earlier migration. Nothing here sends a notification.
--
--   * public.device_push_tokens (baseline, retired since F1B, never wired) is
--     reshaped into "one row per installation": installation_id, provider
--     (fcm | apns), APNs environment, token_updated_at. It must be EMPTY: the
--     preconditions abort otherwise (the read-only pack
--     docs/native/NATIVE_NOTIFICATIONS_V1_PREFLIGHT.sql shows the count first).
--   * Client roles lose every table privilege and both legacy policies: tokens
--     are reachable only through the two RPCs below and by the service role
--     (the Edge dispatcher).
--   * register_native_push_device: identity from auth.uid() only, a real
--     non-anonymous auth user, a profile and a current couple; bounded token
--     shape per provider; the same token on another installation is removed
--     (token moved). An installation id already owned by another account is
--     never taken over: auth.uid() remains authoritative.
--   * unregister_native_push_device: removes ONE installation only when it is
--     owned by auth.uid(). Other users' and other devices' rows are untouched.
--     Offline logout still unregisters at the OS/provider and rotates the
--     installation id; a stale server row is later pruned on invalid-token.
--   * register_push_token(text,text) (RETIRED F1B, incompatible shape) is dropped.
--
-- Fails closed: preconditions abort before any change, the self-check aborts
-- if a postcondition does not hold. Re-applying it changes nothing.

do $n2_pre$
declare
  rows_present bigint;
begin
  if to_regclass('public.device_push_tokens') is null then
    raise exception 'N2: public.device_push_tokens missing; production is not in the baseline state';
  end if;
  if not exists (select 1 from information_schema.columns
                 where table_schema = 'public' and table_name = 'device_push_tokens' and column_name = 'installation_id') then
    select count(*) into rows_present from public.device_push_tokens;
    if rows_present > 0 then
      raise exception 'N2: device_push_tokens holds % legacy row(s) without an installation id; review them before applying', rows_present;
    end if;
  end if;
end
$n2_pre$;

