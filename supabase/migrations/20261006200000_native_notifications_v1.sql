-- RPCs -----------------------------------------------------------------------
create or replace function public.register_native_push_device(
  target_installation_id uuid,
  target_platform text,
  target_provider text,
  target_token text,
  target_environment text default null,
  target_retired_installation_id uuid default null
) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  uid uuid := auth.uid();
  cid uuid;
  clean_token text := btrim(coalesce(target_token, ''));
  env text := nullif(btrim(coalesce(target_environment, '')), '');
  row_id uuid;
begin
  if uid is null then raise exception using errcode = '42501', message = 'authentication required'; end if;
  if not exists (select 1 from auth.users u where u.id = uid and not coalesce(u.is_anonymous, false)) then
    raise exception using errcode = '42501', message = 'account required';
  end if;
  select p.couple_id into cid from public.profiles p where p.id = uid;
  if cid is null or not exists (select 1 from public.couples c where c.id = cid) then
    raise exception using errcode = '42501', message = 'couple membership required';
  end if;
  if target_installation_id is null then raise exception using errcode = '22023', message = 'installation_invalid'; end if;
  if target_platform is null or target_provider is null then raise exception using errcode = '22023', message = 'platform_invalid'; end if;
  if not ((target_platform = 'android' and target_provider = 'fcm' and env is null)
       or (target_platform = 'ios' and target_provider = 'apns' and env is not null and env in ('development', 'production'))) then
    raise exception using errcode = '22023', message = 'platform_invalid';
  end if;
  if not ((target_provider = 'fcm' and length(clean_token) between 32 and 4096 and clean_token ~ '^[A-Za-z0-9_:-]+$')
       or (target_provider = 'apns' and length(clean_token) between 64 and 200 and clean_token ~ '^[0-9a-f]+$')) then
    raise exception using errcode = '22023', message = 'token_invalid';
  end if;

  -- Best-effort cleanup of an offline-retired installation. SECURITY DEFINER
  -- never treats the UUID itself as authorization: only this authenticated
  -- user's stale row may be removed. A retired row belonging to a previous
  -- account remains harmless because the native token was unregistered at
  -- logout and is pruned when the provider reports it invalid.
  if target_retired_installation_id is not null and target_retired_installation_id <> target_installation_id then
    delete from public.device_push_tokens d
    where d.installation_id = target_retired_installation_id
      and d.user_id = uid;
  end if;
  -- The provider token may move between installations of the SAME account
  -- (reinstall / restored app data). A token string is not authorization and
  -- can never be used to delete or take over another user's row.
  delete from public.device_push_tokens d
  where d.token = clean_token
    and d.installation_id <> target_installation_id
    and d.user_id = uid;

  insert into public.device_push_tokens as d
    (user_id, couple_id, installation_id, token, platform, provider, apns_environment, created_at, last_seen_at, token_updated_at)
  values (uid, cid, target_installation_id, clean_token, target_platform, target_provider, env, now(), now(), now())
  on conflict (installation_id) do update set
    couple_id = excluded.couple_id,
    token = excluded.token,
    platform = excluded.platform,
    provider = excluded.provider,
    apns_environment = excluded.apns_environment,
    last_seen_at = now(),
    token_updated_at = case when d.token is distinct from excluded.token then now() else d.token_updated_at end
  where d.user_id = uid
  returning d.id into row_id;

  if row_id is null then
    raise exception using errcode = '42501', message = 'installation owned by another account';
  end if;

  return jsonb_build_object('active', true, 'platform', target_platform, 'provider', target_provider);
end;
$$;

create or replace function public.unregister_native_push_device(target_installation_id uuid) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  removed integer := 0;
begin
  if auth.uid() is null then raise exception using errcode = '42501', message = 'authentication required'; end if;
  if target_installation_id is null then return jsonb_build_object('removed', false); end if;
  delete from public.device_push_tokens d
  where d.installation_id = target_installation_id
    and d.user_id = auth.uid();
  get diagnostics removed = row_count;
  return jsonb_build_object('removed', removed > 0);
end;
$$;

comment on function public.register_native_push_device(uuid, text, text, text, text, uuid) is
  'Native Notifications V1: registers this app installation''s FCM/APNs token for auth.uid() in its current couple.';
comment on function public.unregister_native_push_device(uuid) is
  'Native Notifications V1: removes one installation registration only when it belongs to auth.uid().';

revoke all on function public.register_native_push_device(uuid, text, text, text, text, uuid) from public, anon;
revoke all on function public.unregister_native_push_device(uuid) from public, anon;
grant execute on function public.register_native_push_device(uuid, text, text, text, text, uuid) to authenticated;
grant execute on function public.unregister_native_push_device(uuid) to authenticated;

