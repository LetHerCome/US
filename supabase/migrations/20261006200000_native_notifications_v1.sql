-- Self-check ------------------------------------------------------------------
do $n2_post$
begin
  if has_table_privilege('authenticated', 'public.device_push_tokens', 'SELECT')
     or has_table_privilege('authenticated', 'public.device_push_tokens', 'INSERT')
     or has_table_privilege('authenticated', 'public.device_push_tokens', 'UPDATE')
     or has_table_privilege('authenticated', 'public.device_push_tokens', 'DELETE')
     or has_table_privilege('anon', 'public.device_push_tokens', 'SELECT')
     or has_table_privilege('anon', 'public.device_push_tokens', 'INSERT')
     or has_table_privilege('anon', 'public.device_push_tokens', 'UPDATE')
     or has_table_privilege('anon', 'public.device_push_tokens', 'DELETE') then
    raise exception 'N2: a client role can still read or write device_push_tokens';
  end if;
  if has_function_privilege('anon', 'public.register_native_push_device(uuid,text,text,text,text,uuid)', 'EXECUTE')
     or has_function_privilege('anon', 'public.unregister_native_push_device(uuid)', 'EXECUTE') then
    raise exception 'N2: anon can execute a native push RPC';
  end if;
  if not has_function_privilege('authenticated', 'public.register_native_push_device(uuid,text,text,text,text,uuid)', 'EXECUTE')
     or not has_function_privilege('authenticated', 'public.unregister_native_push_device(uuid)', 'EXECUTE') then
    raise exception 'N2: authenticated lost EXECUTE on a native push RPC';
  end if;
  if to_regprocedure('public.register_push_token(text,text)') is not null then
    raise exception 'N2: the retired register_push_token still exists';
  end if;
  if not exists (select 1 from pg_constraint where conrelid = 'public.device_push_tokens'::regclass and conname = 'device_push_tokens_installation_id_key') then
    raise exception 'N2: device_push_tokens_installation_id_key missing';
  end if;
end
$n2_post$;
